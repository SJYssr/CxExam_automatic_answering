/**
 * 生成 RSA 2048 密钥对，用于 AES+RSA 混合加密：
 * - native_decrypt/key.h：嵌入 RSA 私钥 PEM（仅原生模块持有，运行时解密用）
 * - scripts/rsa_public.pem：RSA 公钥（打包时 encrypt-asar.js 用其加密每文件的随机 AES 密钥）
 * 仅需运行一次；重新运行将生成新密钥（需重新 build:decrypt 与打包）。
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');

const { publicKey, privateKey } = crypto.generateKeyPairSync('rsa', {
  modulusLength: 2048,
  publicKeyEncoding:  { type: 'spki', format: 'pem' },
  privateKeyEncoding: { type: 'pkcs1', format: 'pem' }
});

// 将 PEM 转为 C 头文件中的字符串字面量（按行拼接，避免超长行）
function pemToCString(pem) {
  const lines = pem.split(/\r?\n/).filter(Boolean);
  return lines.map(line => '"' + line.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '\\n"').join('\n');
}

// 写入 native_decrypt/key.h（仅 RSA 私钥，供原生模块运行时解密用）
const keyH = `#ifndef _KEY_H_
#define _KEY_H_

/* RSA private key PEM, generated by scripts/generate-key.js. Do not commit to public repo. */
static const char RSA_PRIVATE_KEY_PEM[] =
${pemToCString(privateKey)}
"";

#endif
`;
fs.writeFileSync(path.join(root, 'native_decrypt', 'key.h'), keyH, 'utf8');
console.log('已写入 native_decrypt/key.h（RSA 私钥）');

// 写入 scripts/rsa_public.pem（打包时加密脚本使用）
const publicPath = path.join(__dirname, 'rsa_public.pem');
fs.writeFileSync(publicPath, publicKey, 'utf8');
console.log('已写入 scripts/rsa_public.pem');

console.log('\n请执行: npm run build:decrypt  重新编译原生模块后再打包。');
console.log('建议将 rsa_public.pem 加入 .gitignore（若需私钥仅本地），或仅提交公钥以允许他人打包。');
