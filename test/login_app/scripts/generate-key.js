/**
 * 生成 32 字节加密安全随机密钥，并同步写入：
 * - native_decrypt/key.h（C 头文件，供原生模块编译）
 * - scripts/asar-key.hex（64 位 hex，供打包时 encrypt-asar.js 读取）
 * 仅需运行一次；之后打包会使用该密钥。重新运行将生成新密钥（需重新 build:decrypt 与打包）。
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

function chunk(arr, n) {
  const out = [];
  for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
  return out;
}

const root = path.join(__dirname, '..');
const keyBytes = crypto.randomBytes(32);

// 写入 native_decrypt/key.h
const keyH = `#ifndef _KEY_H_
#define _KEY_H_

#include <stdint.h>

/* 32-byte AES-256 key, generated by scripts/generate-key.js. Do not commit asar-key.hex if you need to keep the key private. */
#define AES_KEY_BYTES 32
static const uint8_t AES_KEY[AES_KEY_BYTES] = {
${chunk(Array.from(keyBytes), 8)
  .map(row => '    ' + row.map(b => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',')
  .join('\n')}
};

#endif
`;
fs.writeFileSync(path.join(root, 'native_decrypt', 'key.h'), keyH, 'utf8');
console.log('已写入 native_decrypt/key.h');

// 写入 scripts/asar-key.hex（64 位 hex，encrypt-asar.js 会读取）
const hexPath = path.join(__dirname, 'asar-key.hex');
fs.writeFileSync(hexPath, keyBytes.toString('hex'), 'utf8');
console.log('已写入 scripts/asar-key.hex');

console.log('\n请执行: npm run build:decrypt  重新编译原生模块后再打包。');
console.log('建议将 asar-key.hex 加入 .gitignore，避免密钥进入版本库。');
